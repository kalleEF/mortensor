test_that("ungrouping diagnostics compare methods against known single years", {
  xs <- mt_example(deaths = "single", years = 2010:2013)
  x <- mt_regroup(xs, age = c(30, seq(40, 90, 10)), measures = "deaths")
  expect_true(all(mt_obs(x, "deaths")$age_hi - mt_obs(x, "deaths")$age_lo >= 10))
  expect_identical(nrow(mt_obs(x, "exposure")), nrow(mt_obs(xs, "exposure")))
  u <- list(PCLM = mt_ungroup(x), spline = mt_ungroup(x, method = "hyman_kannisto"))
  chk <- mt_ungroup_check(u, reference = xs)
  expect_setequal(as.character(chk$method), c("PCLM", "spline"))
  expect_true(all(c("mae_log", "noise_log", "bias_log", "at_bound", "max_rel_gap") %in% names(chk)))
  # the estimates are about as close to the known rates as Poisson noise allows
  expect_lt(max(chk$mae_log / chk$noise_log), 2)
  expect_identical(nrow(mt_ungroup_check(u$PCLM)), 1L)
  expect_error(mt_ungroup_check(list(u$PCLM)), class = "mt_error_argument")
  expect_error(mt_regroup(xs, age = c(30, 40), measures = "population"), class = "mt_error_argument")
  skip_if_not_installed("ggplot2")
  expect_s3_class(mt_plot_ungroup(x, u, 2012), "ggplot")
  expect_s3_class(mt_plot_ungroup(x, u, type = "time", strata = "female"), "ggplot")
  expect_s3_class(mt_plot_ungroup(x, u, type = "time", reference = xs, ages = c(45, 85)), "ggplot")
  expect_s3_class(mt_plot_ungroup(x, u, type = "error", reference = xs), "ggplot")
  expect_error(mt_plot_ungroup(x, u, type = "error"), class = "mt_error_argument")
})

test_that("stratified() fits different models to groups of strata", {
  x <- mt_example(deaths = "single", years = 1990:2019)
  spec <- stratified("sex", female = lee_carter(), .default = rwd())
  fit <- mt_fit(spec, x)
  expect_s3_class(fit, "mt_fit_split")
  expect_match(spec$label, "female: Lee-Carter")
  fc <- mt_forecast(fit, h = 5, n_draws = 30, seed = 1)
  expect_identical(dim(fc$rates)[3], 2L)
  expect_true(all(is.finite(fc$rates)))
  bt <- mt_backtest(spec, x, origins = 2012, h = 3, n_draws = 30)
  expect_true(all(c("female", "male") %in% bt$sex))
  h <- mt_hierarchy(sex = "both")
  xa <- mt_aggregate_strata(x, h)
  rc <- mt_forecast(mt_fit(reconciled(stratified("sex", both = lee_carter(), .default = li_lee()), h,
                                      method = "proportional", fixed = "both"), xa), h = 5, n_draws = 30, seed = 1)
  co <- mt_coherence(rc, h)
  expect_lt(max(abs(co$q0.5 - 1)), 1e-8)
  expect_error(mt_fit(stratified("sex", female = lee_carter()), x), class = "mt_error_argument")
  expect_error(mt_fit(stratified("sex", woman = lee_carter(), .default = rwd()), x), class = "mt_error_argument")
  expect_error(stratified("sex", lee_carter()), class = "mt_error_argument")
})
